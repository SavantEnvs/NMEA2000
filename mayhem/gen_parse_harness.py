#!/usr/bin/env python3
"""Regenerate mayhem/fuzz_n2kmessages.cpp from the ParseN2k*PGN<n>* decoder declarations in
src/N2kMessages.h, src/N2kCZone.h and src/N2kMaretron.h (in that order: new headers append, so the
selector byte of existing seeds keeps meaning the same decoder).

Usage (from the repo root): python3 mayhem/gen_parse_harness.py > mayhem/fuzz_n2kmessages.cpp
"""
import re
import sys

HEADERS = ["N2kMessages.h", "N2kCZone.h", "N2kMaretron.h"]
decls = []
for h in HEADERS:
    src = open("src/" + h).read()
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    src = re.sub(r"//[^\n]*", "", src)
    decls += re.findall(r"\bbool\s+(ParseN2k(?:Maretron)?PGN(\d+)\w*)\s*\(([^{};]*)\)\s*;", src)
seen, funcs = set(), []
for name, pgn, params in decls:
    if name in seen:
        continue
    seen.add(name)
    funcs.append((name, int(pgn), [" ".join(p.split()) for p in params.split(",")]))

out = []
out.append("""// Generated by mayhem/gen_parse_harness.py from src/N2kMessages.h, src/N2kCZone.h and src/N2kMaretron.h
// -- do not edit by hand.
//
// Fuzzes every ParseN2k*PGN<n>*() decoder of the library (standard, CZone, Maretron): the bytes after the
// selector byte are the data field of a received NMEA2000 message, exactly what an application hands to
// these functions after tNMEA2000::ParseMessages() delivered it from the bus.
#include <stddef.h>
#include <stdint.h>
#include <string.h>

#include "N2kMessages.h"
#include "N2kCZone.h"
#include "N2kMaretron.h"

extern "C" int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {
  if (size < 1) return -1;
  // tN2kMsg::Data holds at most tN2kMsg::MaxDataLen bytes (N2kMsg.h); a longer data field cannot exist.
  if (size - 1 > (size_t)tN2kMsg::MaxDataLen) return -1;

  tN2kMsg msg;
  msg.DataLen = (int)(size - 1);
  memcpy(msg.Data, data + 1, size - 1);
  msg.Source = 0;
  msg.Destination = 255;

  switch (data[0] % @N@) {""".replace("@N@", str(len(funcs))))

for i, (name, pgn, params) in enumerate(funcs):
    decl, args = [], []
    k = 0
    j = 0
    while j < len(params):
        p = re.sub(r"=.*", "", params[j]).strip()
        m = re.match(r"^(.*?)\s*([&*]*)\s*(\w+)$", p)
        typ, ref, nm = m.group(1).strip(), m.group(2), m.group(3)
        if typ == "const tN2kMsg":
            args.append("msg")
        elif typ == "char" and ref == "*":
            decl.append("char b%d[64]; size_t s%d = sizeof(b%d);" % (k, k, k))
            args.append("b%d" % k)
            j += 1  # the size parameter that follows
            args.append("s%d" % k)
            k += 1
        else:
            decl.append("%s v%d{};" % (typ, k))
            args.append("v%d" % k)
            k += 1
        j += 1
    out.append("    case %d: {  // PGN %d" % (i, pgn))
    for d in decl:
        out.append("      " + d)
    out.append("      msg.PGN = %dUL;" % pgn)
    out.append("      %s(%s);" % (name, ", ".join(args)))
    out.append("      break;\n    }")
out.append("""  }
  return 0;
}""")
sys.stdout.write("\n".join(out) + "\n")
